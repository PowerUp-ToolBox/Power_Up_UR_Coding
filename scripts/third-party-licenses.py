#!/usr/bin/env python3
"""Writes rust/THIRD-PARTY-LICENSES.md: every third-party crate the Rust
workspace depends on, with its version and license (#141).

CI regenerates the file and fails when it differs from the checked-in copy,
so a dependency change always shows up in review with its license.

Usage (from the repository root): python3 scripts/third-party-licenses.py
"""
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
RUST = ROOT / "rust"
OUT = RUST / "THIRD-PARTY-LICENSES.md"


def main() -> int:
    metadata = json.loads(subprocess.run(
        ["cargo", "metadata", "--format-version", "1", "--locked"],
        cwd=RUST, check=True, capture_output=True, text=True).stdout)
    workspace = set(metadata["workspace_members"])
    crates = sorted(
        (p for p in metadata["packages"] if p["id"] not in workspace),
        key=lambda p: (p["name"].lower(), p["version"]))
    lines = [
        "# Third-party Rust crates",
        "",
        "Generated by `scripts/third-party-licenses.py` from `rust/Cargo.lock`;",
        "do not edit by hand. CI fails when it is stale. The allowed licenses",
        "are set in `rust/deny.toml`.",
        "",
        "| Crate | Version | License | Source |",
        "| --- | --- | --- | --- |",
    ]
    for p in crates:
        license_ = (p.get("license") or "see license file").replace("|", "\\|")
        source = p.get("repository") or ""
        lines.append(f"| {p['name']} | {p['version']} | {license_} | {source} |")
    OUT.write_text("\n".join(lines) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)} ({len(crates)} crates)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
