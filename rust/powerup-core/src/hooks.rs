//! The Claude Code hooks PowerUp registers in `~/.claude/settings.json`, so
//! replies from any claude session on the machine can be read back
//! (DESIGN v1.6, v2.14): the command registered, the hook script's text,
//! installing and removing the hooks, and whether they are installed as the
//! app runs now.
//!
//! settings.json belongs to the person and other tools write to it too, so
//! every edit is conservative: unknown keys and foreign hooks are copied
//! through, a file that is not a JSON object is refused, and a `hooks` or
//! event value of an unexpected shape is refused rather than overwritten.
//!
//! The platform keeps the files: it reads the settings and the script, and
//! writes them. The file is read here as Foundation's `JSONSerialization`
//! reads it (the slice 2.3 reader), and an edit comes back as compact JSON
//! that keeps every number literal as written ([`json::write_verbatim`]),
//! for the platform's own writer: on macOS, `JSONSerialization` with sorted
//! keys, whose collation and number spelling the core does not reproduce
//! (HK-417).
//!
//! A command is PowerUp's when it equals the quoted script path or the
//! legacy unquoted path byte for byte (HK-183, HK-418), and the script on
//! disk is compared with the current body byte for byte too.

use std::collections::HashSet;

use unicode_segmentation::UnicodeSegmentation;

use crate::json::{self, JsonValue};
use crate::{text, CoreError};

/// The hook events PowerUp subscribes to, in a stable order (HK-180).
/// SessionEnd is how a session that closes mid-turn releases the "Claude
/// is working" state (its Stop hook never fires); PostToolUse is the turn's
/// heartbeat, fired on every tool call.
pub const HOOK_EVENTS: [&str; 5] = [
    "Stop",
    "UserPromptSubmit",
    "Notification",
    "SessionEnd",
    "PostToolUse",
];

/// The command registered for the hook script (HK-181). Claude Code runs it
/// through a shell, and the script lives under "Application Support": an
/// unquoted path with a space splits into a command that does not exist,
/// and every hook dies silently. So the path goes in single quotes, each
/// single quote in it written as `'\''`; a quote that a combining mark
/// joins into another character is not one (as Foundation's
/// `replacingOccurrences` finds it).
pub fn hook_command(script_path: &str) -> String {
    format!("'{}'", text::replace_clusters(script_path, "'", "'\\''"))
}

/// The hook script for a listener port and token (HK-184 to HK-186). It
/// reads the event payload from stdin before it backgrounds curl, so the
/// payload is never lost, and always exits 0 at once, so PowerUp being
/// closed, busy or on another port never delays Claude. The port is clamped
/// to 1...65535 and the token escaped for a double-quoted bash string.
pub fn hook_script_body(port: i64, token: &str) -> String {
    let port = port.clamp(1, 65535);
    let token = shell_double_quoted(token);
    format!(
        "#!/bin/bash\n\
         # PowerUp hook \u{2014} forwards Claude Code hook events to the PowerUp app.\n\
         #\n\
         # Generated by PowerUp (Settings \u{2192} Remote). Safe to delete: without it the\n\
         # app simply loses spoken read-back from terminal/cmux sessions.\n\
         #\n\
         # stdin is consumed BEFORE curl is backgrounded, so the payload can never\n\
         # be lost, and the script always exits 0 immediately \u{2014} Claude is never\n\
         # delayed or blocked by PowerUp being closed, busy, or on another port.\n\
         payload=$(cat)\n\
         curl -s -o /dev/null --max-time 1 \\\n     \
         -X POST \\\n     \
         -H \"Content-Type: application/json\" \\\n     \
         -H \"X-PowerUp-Token: {token}\" \\\n     \
         --data-binary \"$payload\" \\\n     \
         \"http://127.0.0.1:{port}/event\" >/dev/null 2>&1 &\n\
         exit 0\n"
    )
}

/// A value for a double-quoted bash string, Character by Character as the
/// Swift app escaped it: backslash, double quote, dollar and backtick get a
/// backslash, and a Character equal to LF or CR is dropped (HK-185). Swift
/// compares Characters by canonical equivalence, so U+1FEF GREEK VARIA,
/// which decomposes to a backtick, is escaped too; CR LF is one Character
/// equal to neither, and a mark that joins a backslash makes it another
/// Character, so both stay as they are.
fn shell_double_quoted(value: &str) -> String {
    let mut escaped = String::with_capacity(value.len());
    for character in value.graphemes(true) {
        match character {
            "\\" | "\"" | "$" | "`" | "\u{1FEF}" => {
                escaped.push('\\');
                escaped.push_str(character);
            }
            "\n" | "\r" => {}
            _ => escaped.push_str(character),
        }
    }
    escaped
}

/// How the registered hooks relate to the port and token the app uses now.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum InstallState {
    NotInstalled,
    /// Registered for every event, and the script carries the current port
    /// and token.
    Installed,
    /// Registered but stale: an event is missing, the registration is the
    /// legacy unquoted path, or the script is missing or was written for
    /// another port or token. Reinstalling fixes it.
    OutOfDate,
}

impl InstallState {
    /// The Swift case name, as the fixtures spell it.
    pub fn name(self) -> &'static str {
        match self {
            InstallState::NotInstalled => "notInstalled",
            InstallState::Installed => "installed",
            InstallState::OutOfDate => "outOfDate",
        }
    }
}

/// Why an edit left the settings file alone.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SettingsRefusal {
    /// The file is not a JSON object.
    InvalidJson,
    /// `hooks` is there and is not an object (null included).
    HooksNotAnObject,
    /// An event PowerUp registers is there and is not an array.
    EventNotAnArray { event: String },
}

/// What an install or uninstall does to the settings file.
#[derive(Debug, Clone, PartialEq, Eq)]
pub enum SettingsEdit {
    /// Nothing changes: the file is not written and no backup is taken.
    Unchanged,
    /// The whole new file, as compact JSON for the platform's writer to
    /// format (see the module documentation).
    Write { json: String },
    /// The file is left as it is, for this reason.
    Refused(SettingsRefusal),
}

/// True when the Stop hook points at the script, quoted or as the legacy
/// unquoted path (HK-189). `settings` is the file's bytes, `None` for no
/// file.
pub fn is_installed(settings: Option<&[u8]>, script_path: &str) -> bool {
    let Ok(root) = read_settings(settings) else {
        return false;
    };
    let command = hook_command(script_path);
    stop_groups(&root).is_some_and(|groups| {
        groups
            .iter()
            .any(|group| group_references(group, &[&command, script_path]))
    })
}

/// The full state for Settings (HK-187 to HK-189): not just "is the path
/// registered" but "will the hooks reach the listener as configured now".
/// `script_on_disk` is the script file's bytes, `None` when there is none.
pub fn install_state(
    settings: Option<&[u8]>,
    script_path: &str,
    script_on_disk: Option<&[u8]>,
    port: i64,
    token: &str,
) -> InstallState {
    let Ok(root) = read_settings(settings) else {
        return InstallState::NotInstalled;
    };
    let Some(groups) = stop_groups(&root) else {
        return InstallState::NotInstalled;
    };
    let command = hook_command(script_path);
    let has_quoted = groups
        .iter()
        .any(|group| group_references(group, &[&command]));
    let has_legacy = groups
        .iter()
        .any(|group| group_references(group, &[script_path]));
    if !has_quoted {
        // A legacy registration never runs (the space splits the command).
        return if has_legacy {
            InstallState::OutOfDate
        } else {
            InstallState::NotInstalled
        };
    }
    // An install from an older build may lack an event added since.
    let hooks = root.get("hooks");
    let every_event = HOOK_EVENTS.iter().all(|event| {
        hooks
            .and_then(|hooks| hooks.get(event))
            .and_then(JsonValue::as_array)
            .is_some_and(|groups| {
                groups
                    .iter()
                    .any(|group| group_references(group, &[&command]))
            })
    });
    if !every_event {
        return InstallState::OutOfDate;
    }
    match script_on_disk {
        Some(script) if String::from_utf8_lossy(script) == hook_script_body(port, token) => {
            InstallState::Installed
        }
        _ => InstallState::OutOfDate,
    }
}

/// Merges PowerUp's hooks into the settings (HK-190 to HK-192): for each of
/// the five events in order, entries of the legacy unquoted path are
/// removed (a group left empty goes), and when no group holds the quoted
/// command, `{"hooks":[{"type":"command","command":…}]}` is appended.
/// Idempotent, and `Unchanged` when nothing changed.
pub fn install_edit(settings: Option<&[u8]>, script_path: &str) -> Result<SettingsEdit, CoreError> {
    let mut root = match read_settings(settings) {
        Ok(root) => root,
        Err(refusal) => return Ok(SettingsEdit::Refused(refusal)),
    };
    let command = hook_command(script_path);
    let JsonValue::Object(members) = &mut root else {
        return Ok(SettingsEdit::Refused(SettingsRefusal::InvalidJson));
    };
    keep_first_members(members);
    let mut hooks = match take_member(members, "hooks").as_mut().map(take_object) {
        None => Vec::new(),
        Some(Some(mut hooks)) => {
            keep_first_members(&mut hooks);
            hooks
        }
        Some(None) => return Ok(SettingsEdit::Refused(SettingsRefusal::HooksNotAnObject)),
    };

    let mut changed = false;
    for event in HOOK_EVENTS {
        let mut groups = match take_member(&mut hooks, event).as_mut().map(take_array) {
            None => Vec::new(),
            Some(Some(groups)) => groups,
            Some(None) => {
                return Ok(SettingsEdit::Refused(SettingsRefusal::EventNotAnArray {
                    event: event.to_owned(),
                }))
            }
        };
        if remove_entries(&mut groups, &[script_path]) {
            changed = true;
        }
        if !groups
            .iter()
            .any(|group| group_references(group, &[&command]))
        {
            groups.push(our_group(&command));
            changed = true;
        }
        put_member(&mut hooks, event, JsonValue::Array(groups));
    }

    if !changed {
        return Ok(SettingsEdit::Unchanged);
    }
    put_member(members, "hooks", JsonValue::Object(hooks));
    Ok(SettingsEdit::Write {
        json: json::write_verbatim(&root)?,
    })
}

/// Removes only PowerUp's entries (HK-195): every event whose value is an
/// array is rebuilt without the entries whose command is the quoted or the
/// legacy path (a group left empty goes, a group of another shape stays);
/// an event left empty is removed, including one that was already empty
/// when anything else changed (kept from the Swift app); an empty `hooks`
/// is removed too. `Unchanged` when nothing was found, and for no file.
pub fn uninstall_edit(
    settings: Option<&[u8]>,
    script_path: &str,
) -> Result<SettingsEdit, CoreError> {
    if settings.is_none() {
        return Ok(SettingsEdit::Unchanged);
    }
    let mut root = match read_settings(settings) {
        Ok(root) => root,
        Err(refusal) => return Ok(SettingsEdit::Refused(refusal)),
    };
    let command = hook_command(script_path);
    let JsonValue::Object(members) = &mut root else {
        return Ok(SettingsEdit::Refused(SettingsRefusal::InvalidJson));
    };
    keep_first_members(members);
    let mut hooks = match take_member(members, "hooks").as_mut().map(take_object) {
        None => return Ok(SettingsEdit::Unchanged),
        Some(Some(hooks)) => hooks,
        Some(None) => return Ok(SettingsEdit::Refused(SettingsRefusal::HooksNotAnObject)),
    };
    keep_first_members(&mut hooks);

    let mut changed = false;
    for (_, value) in &mut hooks {
        if let JsonValue::Array(groups) = value {
            if remove_entries(groups, &[&command, script_path]) {
                changed = true;
            }
        }
    }
    if !changed {
        return Ok(SettingsEdit::Unchanged);
    }
    hooks.retain(|(_, value)| !matches!(value, JsonValue::Array(groups) if groups.is_empty()));
    if hooks.is_empty() {
        members.retain(|(name, _)| name != "hooks");
    } else {
        put_member(members, "hooks", JsonValue::Object(hooks));
    }
    Ok(SettingsEdit::Write {
        json: json::write_verbatim(&root)?,
    })
}

/// The settings as a JSON object: no file, or one that is blank after
/// trimming whitespace and newlines, is `{}`; anything else must read as an
/// object.
fn read_settings(settings: Option<&[u8]>) -> Result<JsonValue, SettingsRefusal> {
    let Some(bytes) = settings else {
        return Ok(JsonValue::Object(Vec::new()));
    };
    if text::trim(&String::from_utf8_lossy(bytes)).is_empty() {
        return Ok(JsonValue::Object(Vec::new()));
    }
    match json::read(bytes) {
        Some(root @ JsonValue::Object(_)) => Ok(root),
        _ => Err(SettingsRefusal::InvalidJson),
    }
}

/// `hooks.Stop` when `hooks` is an object and `Stop` an array.
fn stop_groups(root: &JsonValue) -> Option<&[JsonValue]> {
    root.get("hooks")?.as_object()?;
    root.get("hooks")?.get("Stop")?.as_array()
}

/// True when a group (`{"hooks":[…]}`) holds an entry whose command is one
/// of `commands`.
fn group_references(group: &JsonValue, commands: &[&str]) -> bool {
    group
        .get("hooks")
        .and_then(JsonValue::as_array)
        .is_some_and(|entries| entries.iter().any(|entry| is_ours(entry, commands)))
}

/// True when an entry (`{"type":"command","command":"…"}`) runs one of
/// `commands`, compared byte for byte.
fn is_ours(entry: &JsonValue, commands: &[&str]) -> bool {
    entry
        .get("command")
        .and_then(JsonValue::as_str)
        .is_some_and(|command| commands.contains(&command))
}

/// Removes the entries of `commands` from each group, dropping a group left
/// empty; a group that is not an object with a `hooks` array stays as it
/// is. True when anything was removed. Values move, never copy: a foreign
/// value may be hundreds of containers deep.
fn remove_entries(groups: &mut Vec<JsonValue>, commands: &[&str]) -> bool {
    let mut removed = false;
    let mut rebuilt = Vec::with_capacity(groups.len());
    for mut group in std::mem::take(groups) {
        let Some(JsonValue::Array(entries)) = first_member_mut(&mut group, "hooks") else {
            rebuilt.push(group);
            continue;
        };
        let before = entries.len();
        entries.retain(|entry| !is_ours(entry, commands));
        if entries.len() == before {
            rebuilt.push(group);
            continue;
        }
        removed = true;
        if !entries.is_empty() {
            rebuilt.push(group);
        }
    }
    *groups = rebuilt;
    removed
}

fn our_group(command: &str) -> JsonValue {
    JsonValue::Object(vec![(
        "hooks".to_owned(),
        JsonValue::Array(vec![JsonValue::Object(vec![
            ("type".to_owned(), JsonValue::String("command".to_owned())),
            ("command".to_owned(), JsonValue::String(command.to_owned())),
        ])]),
    )])
}

fn first_member_mut<'a>(object: &'a mut JsonValue, key: &str) -> Option<&'a mut JsonValue> {
    match object {
        JsonValue::Object(members) => members
            .iter_mut()
            .find(|(name, _)| name == key)
            .map(|(_, value)| value),
        _ => None,
    }
}

/// Drops every member whose key an earlier member already has, as
/// Foundation's dictionary holds only the first: an edit that removes a
/// member must not uncover a later one of the same name.
fn keep_first_members(members: &mut Vec<(String, JsonValue)>) {
    let mut seen = HashSet::new();
    let mut kept = Vec::with_capacity(members.len());
    for (key, value) in std::mem::take(members) {
        if seen.insert(key.clone()) {
            kept.push((key, value));
        }
    }
    *members = kept;
}

/// Takes `key`'s value out, leaving a null in its place (or nothing, when
/// there is no such member); [`put_member`] puts a value back there.
fn take_member(members: &mut [(String, JsonValue)], key: &str) -> Option<JsonValue> {
    members
        .iter_mut()
        .find(|(name, _)| name == key)
        .map(|(_, value)| std::mem::replace(value, JsonValue::Null))
}

/// An object's members, moved out; `None` for any other value.
fn take_object(value: &mut JsonValue) -> Option<Vec<(String, JsonValue)>> {
    match value {
        JsonValue::Object(members) => Some(std::mem::take(members)),
        _ => None,
    }
}

/// An array's items, moved out; `None` for any other value.
fn take_array(value: &mut JsonValue) -> Option<Vec<JsonValue>> {
    match value {
        JsonValue::Array(items) => Some(std::mem::take(items)),
        _ => None,
    }
}

/// Sets `key` where it is, or appends it.
fn put_member(members: &mut Vec<(String, JsonValue)>, key: &str, value: JsonValue) {
    match members.iter_mut().find(|(name, _)| name == key) {
        Some((_, slot)) => *slot = value,
        None => members.push((key.to_owned(), value)),
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    const PATH: &str = "/tmp/x y/powerup-hook.sh";

    fn edit_json(edit: Result<SettingsEdit, CoreError>) -> String {
        match edit {
            Ok(SettingsEdit::Write { json }) => json,
            other => panic!("expected a write, got {other:?}"),
        }
    }

    #[test]
    fn the_command_is_single_quoted() {
        assert_eq!(hook_command(PATH), "'/tmp/x y/powerup-hook.sh'");
        assert_eq!(hook_command("/a'b"), "'/a'\\''b'");
    }

    #[test]
    fn a_fresh_install_appends_one_group_per_event() {
        let json = edit_json(install_edit(None, PATH));
        let command = r#"{"hooks":[{"type":"command","command":"'\/tmp\/x y\/powerup-hook.sh'"}]}"#;
        let expected = format!(
            r#"{{"hooks":{{"Stop":[{command}],"UserPromptSubmit":[{command}],"Notification":[{command}],"SessionEnd":[{command}],"PostToolUse":[{command}]}}}}"#
        );
        assert_eq!(json, expected);
        assert_eq!(
            install_edit(Some(json.as_bytes()), PATH),
            Ok(SettingsEdit::Unchanged)
        );
        assert!(is_installed(Some(json.as_bytes()), PATH));
    }

    #[test]
    fn removing_a_member_never_uncovers_a_later_duplicate() {
        // Foundation's dictionary holds the first Stop only; removing it
        // must not bring the second one back.
        let with_duplicate = r#"{"hooks":{"Stop":[{"hooks":[{"command":"'/tmp/x y/powerup-hook.sh'"}]}],"Stop":[{"hooks":[{"command":"/foreign"}]}]}}"#;
        let json = edit_json(uninstall_edit(Some(with_duplicate.as_bytes()), PATH));
        assert_eq!(json, "{}");
    }

    #[test]
    fn the_script_is_compared_byte_for_byte() {
        let installed = edit_json(install_edit(None, PATH));
        let body = hook_script_body(48738, "tok");
        let state = |script: Option<&[u8]>| {
            install_state(Some(installed.as_bytes()), PATH, script, 48738, "tok")
        };
        assert_eq!(state(Some(body.as_bytes())), InstallState::Installed);
        assert_eq!(
            state(Some(&body.as_bytes()[..body.len() - 1])),
            InstallState::OutOfDate
        );
        assert_eq!(state(None), InstallState::OutOfDate);
    }

    #[test]
    fn a_deep_foreign_value_is_moved_not_walked() {
        let worker = std::thread::Builder::new()
            .stack_size(128 * 1024)
            .spawn(|| {
                let settings = format!(r#"{{"deep":{}{}}}"#, "[".repeat(511), "]".repeat(511));
                install_edit(Some(settings.as_bytes()), PATH)
                    .map(|edit| matches!(edit, SettingsEdit::Write { .. }))
            })
            .unwrap();
        assert_eq!(worker.join().unwrap(), Ok(true));
    }

    #[test]
    fn the_token_is_escaped_per_character() {
        let body = hook_script_body(1, "a\"$`\\\u{1FEF}\n\r\r\nb\\\u{301}");
        assert!(body.contains("X-PowerUp-Token: a\\\"\\$\\`\\\\\\\u{1FEF}\r\nb\\\u{301}\""));
    }
}
